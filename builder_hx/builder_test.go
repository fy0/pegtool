func TestGeneratedParserCompilesAndRunsWithMemoization(t *testing.T) {
	haxe := requireHaxeTool(t, "haxe")

	p := bootstrap.NewParser()
	g, err := p.Parse("grammar.peg", strings.NewReader(`{
class ParserCustomData {
	public var wordActions = 0;
	public function new() {}
}
}
start = &word (word "!" / word) ("," word)* !. { return [c.text, c.data.wordActions]; }
word = [\p{L}]+ { c.data.wordActions++; return c.text; }
collision = first / second
first = "x"
second = "y"
failure = failed? failed? "z" !.
failed = "x"
`))
	if err != nil {
		t.Fatal(err)
	}

	pos := ast.Pos{Filename: "grammar.peg", Line: 1, Col: 1}
	eof := func() *ast.NotExpr {
		expr := ast.NewNotExpr(pos)
		expr.Expr = ast.NewAnyMatcher(pos, ".")
		return expr
	}
	rule := func(name string, exprs ...ast.Expression) *ast.Rule {
		seq := ast.NewSeqExpr(pos)
		seq.Exprs = exprs
		r := ast.NewRule(pos, ast.NewIdentifier(pos, name))
		r.Expr = seq
		return r
	}
	andCode := ast.NewAndCodeExpr(pos)
	andCode.Code = ast.NewCodeBlock(pos, "{ return true; }")
	notCode := ast.NewNotCodeExpr(pos)
	notCode.Code = ast.NewCodeBlock(pos, "{ return false; }")
	code := ast.NewCodeExpr(pos)
	code.Code = ast.NewCodeBlock(pos, "{ return null; }")
	g.Rules = append(g.Rules,
		rule("predicateAnd", andCode, ast.NewLitMatcher(pos, "a"), eof()),
		rule("predicateNot", notCode, ast.NewLitMatcher(pos, "b"), eof()),
		rule("codeProbe", code, eof()),
	)

	var generated bytes.Buffer
	if err := BuildParser(&generated, g, base.OptimizeRefExprByIndex(true)); err != nil {
		t.Fatal(err)
	}
	if strings.Contains(generated.String(), "var vals = [];\n\t\tvar notSkipCode") {
		t.Fatal("generated sequence parser still collects child values")
	}
	if strings.Contains(generated.String(), "hxUnicode") {
		t.Fatal("default generated parser unexpectedly depends on hxUnicode")
	}
	if !strings.Contains(generated.String(), "{R16: [") {
		t.Fatal("default generated parser does not embed its Unicode ranges")
	}

	dir := t.TempDir()
	writeHaxeTestFile(t, filepath.Join(dir, "Parser.hx"), generated.Bytes())
	writeHaxeTestFile(t, filepath.Join(dir, "Main.hx"), []byte(`
class Main {
	static function main() {
		var input = "alpha,\u4e16\u754c," + String.fromCharCode(0x10400);
		var memoized = new Parser("", input, []);
		memoized.memoize = true;
		var memoizedResult:Array<Dynamic> = memoized.parse(null);
		if (memoizedResult[0] != input || memoizedResult[1] != 3) {
			throw 'unexpected memoized parse result: ${memoizedResult}';
		}

		var plain = new Parser("", input, []);
		var plainResult:Array<Dynamic> = plain.parse(null);
		if (plainResult[0] != input || plainResult[1] != 4) {
			throw 'unexpected plain parse result: ${plainResult}';
		}

		var collision = new Parser("", "y", []);
		collision.entrypoint = "collision";
		collision.memoize = true;
		collision.parse(null);

		var memoizedFailure = new Parser("", "z", []);
		memoizedFailure.entrypoint = "failure";
		memoizedFailure.memoize = true;
		memoizedFailure.parse(null);
		var failedResult = memoizedFailure.memo1[0]["failed"];
		if (failedResult == null || failedResult.b) {
			throw "failed rule result was not memoized";
		}

		var plainFailure = new Parser("", "z", []);
		plainFailure.entrypoint = "failure";
		plainFailure.parse(null);
		if (plainFailure.stats.ExprCnt <= memoizedFailure.stats.ExprCnt) {
			throw "failed rule was not reevaluated without memoization";
		}

		for (probe in [
			{entrypoint: "predicateAnd", input: "a"},
			{entrypoint: "predicateNot", input: "b"},
			{entrypoint: "codeProbe", input: ""},
		]) {
			var parser = new Parser("", probe.input, []);
			parser.entrypoint = probe.entrypoint;
			try {
				parser.parse(null);
			} catch (error:Dynamic) {
				throw '${probe.entrypoint}: ${Std.string(error)}';
			}
		}
	}
}
`))

	t.Run("javascript", func(t *testing.T) {
		node := requireHaxeTool(t, "node")
		outputFile := filepath.Join(dir, "parser.js")
		cmd := exec.Command(haxe, "-cp", dir, "-main", "Main", "-js", outputFile)
		if output, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("haxe failed: %v\n%s\nGenerated parser:\n%s", err, output, generated.String())
		}
		cmd = exec.Command(node, outputFile)
		if output, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("generated Haxe parser failed: %v\n%s", err, output)
		}
	})

	t.Run("hashlink", func(t *testing.T) {
		hashlink := requireHaxeTool(t, "hl")
		hashlinkFile := filepath.Join(dir, "parser.hl")
		cmd := exec.Command(haxe, "-cp", dir, "-main", "Main", "-hl", hashlinkFile)
		if output, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("Haxe-to-HashLink compilation failed: %v\n%s", err, output)
		}
		cmd = exec.Command(hashlink, hashlinkFile)
		if output, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("generated HashLink parser failed: %v\n%s", err, output)
		}
	})
}

func TestBuildParserMemoizesNamedRulesOnly(t *testing.T) {
	p := bootstrap.NewParser()
	g, err := p.Parse("", strings.NewReader("start = item \"x\" / item \"y\"\nitem = [a-z]+"))
	if err != nil {
		t.Fatal(err)
	}

	var first bytes.Buffer
	if err := BuildParser(&first, g); err != nil {
		t.Fatal(err)
	}
	var second bytes.Buffer
	if err := BuildParser(&second, g); err != nil {
		t.Fatal(err)
	}
	if first.String() != second.String() {
		t.Fatal("repeated Haxe generation is not deterministic")
	}

	generated := first.String()
	for _, want := range []string{
		"memo1:Array<Map<String, ResultTuple>>;",
		"function getMemoizedRule(rule:Rule):ResultTuple",
		"function setMemoizedRule(pt:Savepoint, rule:Rule",
		"var result = this.getMemoizedRule(rule);",
		"entries[rule.name]",
		"this.setMemoizedRule(startMark, rule, ret.val, ret.ok, this.pt);",
		"function parseExprWrap(expr:AllExpr):RetValOk {\n\t\treturn this.parseExpr(expr);\n\t}",
	} {
		if !strings.Contains(generated, want) {
			t.Fatalf("generated parser missing %q", want)
		}
	}
	for _, unwanted := range []string{
		"Map<Any, ResultTuple>",
		"Map<Rule, ResultTuple>",
		"getMemoized(expr)",
		"setMemoized(pt, expr",
	} {
		if strings.Contains(generated, unwanted) {
			t.Fatalf("generated parser still contains expression memoization %q", unwanted)
		}
	}

	var optimized bytes.Buffer
	if err := BuildParser(&optimized, g, base.Optimize(true)); err != nil {
		t.Fatal(err)
	}
	for _, unwanted := range []string{
		"memo1:Array",
		"getMemoizedRule",
		"setMemoizedRule",
		"parseRuleMemoize",
	} {
		if strings.Contains(optimized.String(), unwanted) {
			t.Fatalf("optimized parser unexpectedly contains %q", unwanted)
		}
	}
}

func TestGeneratedParserUsesHxUnicodeOnRequest(t *testing.T) {
	haxe := requireHaxeTool(t, "haxe")
	node := requireHaxeTool(t, "node")

	p := bootstrap.NewParser()
	g, err := p.Parse("grammar.peg", strings.NewReader(`start = [\p{L}]+`))
	if err != nil {
		t.Fatal(err)
	}

	var generated bytes.Buffer
	if err := BuildParser(&generated, g, UseHxUnicode(true)); err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		`#error "This parser uses hxUnicode. Run 'haxelib install hxUnicode' and compile with '-lib hxUnicode'."`,
		"classes: [hxUnicode.U.L,],",
	} {
		if !strings.Contains(generated.String(), want) {
			t.Fatalf("generated parser missing %q", want)
		}
	}

	dir := t.TempDir()
	writeHaxeTestFile(t, filepath.Join(dir, "Parser.hx"), generated.Bytes())
	writeHaxeTestFile(t, filepath.Join(dir, "Main.hx"), []byte(`
class Main {
	static function main() {
		var parser = new Parser("", String.fromCharCode(0x10400), []);
		parser.parse(null);
	}
}
`))

	outputFile := filepath.Join(dir, "parser.js")
	cmd := exec.Command(haxe, "-cp", dir, "-main", "Main", "-js", outputFile)
	output, err := cmd.CombinedOutput()
	if err == nil {
		t.Fatal("Haxe compilation unexpectedly succeeded without hxUnicode")
	}
	for _, want := range []string{"haxelib install hxUnicode", "-lib hxUnicode"} {
		if !strings.Contains(string(output), want) {
			t.Fatalf("missing actionable hxUnicode diagnostic %q:\n%s", want, output)
		}
	}

	requireHaxeLibrary(t, "hxUnicode")
	cmd = exec.Command(haxe, "-lib", "hxUnicode", "-cp", dir, "-main", "Main", "-js", outputFile)
	if output, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("haxe failed with hxUnicode enabled: %v\n%s\nGenerated parser:\n%s", err, output, generated.String())
	}
	cmd = exec.Command(node, outputFile)
	if output, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("generated Haxe parser failed: %v\n%s", err, output)
	}
}

