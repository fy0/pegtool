func requireHaxeTool(t *testing.T, name string) string {
	t.Helper()
	path, err := exec.LookPath(name)
	if err != nil {
		t.Skipf("%s is not installed", name)
	}
	return path
}

func requireHaxeLibrary(t *testing.T, name string) {
	t.Helper()
	cmd := exec.Command("haxelib", "path", name)
	if err := cmd.Run(); err != nil {
		t.Skipf("Haxe library %s is not installed", name)
	}
}

func writeHaxeTestFile(t *testing.T, path string, value []byte) {
	t.Helper()
	if err := os.WriteFile(path, value, 0o600); err != nil {
		t.Fatal(err)
	}
}
