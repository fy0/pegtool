// Package builder_cs generates self-contained C# PEG parsers.
package builder_cs

import (
	"bytes"
	"fmt"
	"io"
	"strconv"
	"strings"
	"unicode"

	"github.com/fy0/pigeon/ast"
	base "github.com/fy0/pigeon/builder"
)

const codeGeneratedComment = "// Code generated by pigeon; DO NOT EDIT."

// BuildParser builds a C# PEG parser and writes it to w.
func BuildParser(w io.Writer, g *ast.Grammar, opts ...base.Option) error {
	b0 := base.Builder{
		W:           w,
		RecvName:    "c",
		Target:      "cs",
		GrammarName: "g",
		IndentUnit:  "    ",
	}
	b := &Builder{Builder: b0}
	b.Init()
	b.SetOptions(opts)
	return b.BuildParser(g)
}

// Builder adapts the shared grammar traversal to C# syntax.
type Builder struct {
	base.Builder
}

func (b *Builder) Init() {
	b.Builder.Init()

	b.Shims.WriteInit = func(b *base.Builder, init *ast.CodeBlock) {
		b.Writeln(codeGeneratedComment)
		b.Writeln("#nullable enable")
		b.Writeln("using System;")
		b.Writeln("using System.Collections.Generic;")
		b.Writeln("using System.Linq;")
		b.Writeln("using System.Text;")
		b.Writeln("")
		b.Writeln("public sealed partial class PigeonParser")
		b.Writeln("{")
		b.Indent()
		if init == nil {
			return
		}
		value := strings.TrimSpace(b.TemplateRender(init.Val[1:len(init.Val)-1], false))
		if value != "" {
			b.Writeln(value)
			b.Writeln("")
		}
	}

	b.Shims.WriteGrammar = func(b *base.Builder, grammar *ast.Grammar) {
		indexRules(b, grammar)
		b.Writelnf("private static readonly Grammar %s = new Grammar", b.GrammarName)
		b.Writeln("{")
		b.Indent()
		b.Writeln("Rules = new List<Rule>")
		b.Writeln("{")
		b.Indent()
		for _, rule := range grammar.Rules {
			b.WriteRule(rule)
		}
		b.Dedent()
		b.Writeln("},")
		b.Dedent()
		b.Writeln("};")
		b.Writeln("")
	}
	b.Shims.WriteGrammar2 = b.Shims.WriteGrammar

	b.Shims.WriteRule = writeRule
	b.Shims.WriteAndExpr = writeAndExpr
	b.Shims.WriteAnyMatcher = func(b *base.Builder, expr *ast.AnyMatcher) {
		if expr == nil {
			b.WriteNilLine()
			return
		}
		writeExprBlock(b, "Any", b.SetRulePos, func() {
			b.WriteRulePos(expr.Pos())
		})
	}
	b.Shims.WriteActionExpr = writeActionExpr
	b.Shims.WriteAndCodeExpr = func(b *base.Builder, expr *ast.AndCodeExpr) {
		if expr == nil {
			b.WriteNilLine()
			return
		}
		writePredicateExpr(b, "AndCode", expr.FuncIx, expr.Pos(), func(ix int) { expr.FuncIx = ix })
	}
	b.Shims.WriteCharClassMatcher = writeCharClassMatcher
	b.Shims.WriteCodeExpr = writeCodeExpr
	b.Shims.WriteChoiceExpr = writeChoiceExpr
	b.Shims.WriteLabeledExpr = writeLabeledExpr
	b.Shims.WriteLitMatcher = writeLiteral
	b.Shims.WriteNotCodeExpr = func(b *base.Builder, expr *ast.NotCodeExpr) {
		if expr == nil {
			b.WriteNilLine()
			return
		}
		writePredicateExpr(b, "NotCode", expr.FuncIx, expr.Pos(), func(ix int) { expr.FuncIx = ix })
	}
	b.Shims.WriteNotExpr = writeNotExpr
	b.Shims.WriteOneOrMoreExpr = func(b *base.Builder, expr *ast.OneOrMoreExpr) {
		if expr == nil {
			b.WriteNilLine()
			return
		}
		writeUnaryExpr(b, "OneOrMore", expr.Pos(), expr.Expr)
	}
	b.Shims.WriteRecoveryExpr = writeRecoveryExpr
	b.Shims.WriteRuleRefExpr = writeRuleRefExpr
	b.Shims.WriteSeqExpr = writeSequenceExpr
	b.Shims.WriteThrowExpr = writeThrowExpr
	b.Shims.WriteZeroOrMoreExpr = func(b *base.Builder, expr *ast.ZeroOrMoreExpr) {
		if expr == nil {
			b.WriteNilLine()
			return
		}
		writeUnaryExpr(b, "ZeroOrMore", expr.Pos(), expr.Expr)
	}
	b.Shims.WriteZeroOrOneExpr = func(b *base.Builder, expr *ast.ZeroOrOneExpr) {
		if expr == nil {
			b.WriteNilLine()
			return
		}
		writeUnaryExpr(b, "ZeroOrOne", expr.Pos(), expr.Expr)
	}
	b.Shims.WriteFunc = writeFunction

	b.Shims.WriteRulePos = func(b *base.Builder, pos ast.Pos) {
		if b.SetRulePos {
			b.WritelnFieldf("Pos = new Position(%d, %d, %d),", pos.Line, pos.Col, pos.Off)
		}
	}
	b.Shims.WriteStaticCodeWrap = func(b *base.Builder) {
		b.WriteStaticCode(runtimeCode)
	}
	b.Shims.WriteNilLine = func(b *base.Builder) { b.Writeln("null!,") }
	b.Shims.WriteExprBlock = func(b *base.Builder, name string, newline bool, inside func()) {
		writeExprBlock(b, strings.ToUpper(name[:1])+name[1:], newline, inside)
	}
	b.Shims.WriteArray = writeArray
	b.Shims.WriteFooter = func(b *base.Builder) {
		b.Dedent()
		b.Writeln("}")
	}
}

func indexRules(b *base.Builder, grammar *ast.Grammar) {
	b.RuleName2Index = make(map[string]*base.ExprInfo, len(grammar.Rules))
	for index, rule := range grammar.Rules {
		info := b.GetExprInfo(rule.Expr)
		info.Index = index
		b.RuleName2Index[rule.Name.Val] = info
	}
}

func writeRule(b *base.Builder, rule *ast.Rule) {
	if rule == nil || rule.Name == nil {
		return
	}
	b.ExprIndex = 0
	b.RuleName = rule.Name.Val
	if b.Entrypoint == "" {
		b.Entrypoint = rule.Name.Val
	}
	b.Writeln("new Rule")
	b.Writeln("{")
	b.Indent()
	b.Writelnf("Name = %s,", quoteCSharp(rule.Name.Val))
	if rule.DisplayName != nil && rule.DisplayName.Val != "" {
		b.Writelnf("DisplayName = %s,", quoteCSharp(rule.DisplayName.Val))
	}
	if rule.IsLabelExists {
		b.Writeln("VarExists = true,")
	}
	b.WriteRulePos(rule.Pos())
	b.Writef("Expr = ")
	b.WriteExpr(rule.Expr)
	b.Dedent()
	b.Writeln("},")
}

func writeExprBlock(b *base.Builder, kind string, newline bool, inside func()) {
	b.Writef("new Expr { Kind = ExprKind.%s,", kind)
	if newline {
		b.Writeln("")
	}
	b.Indent()
	if inside != nil {
		inside()
	}
	b.Dedent()
	b.Writeln("},")
}

func writeAndExpr(b *base.Builder, expr *ast.AndExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	kind := "And"
	if expr.Logical {
		kind = "AndLogical"
	}
	writeExprBlock(b, kind, true, func() {
		b.WriteRulePos(expr.Pos())
		b.WriteFieldf("Inner = ")
		b.WriteExpr(expr.Expr)
	})
}

func writeActionExpr(b *base.Builder, expr *ast.ActionExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	if expr.FuncIx == 0 {
		expr.FuncIx = b.ExprIndex
	}
	writeExprBlock(b, "Action", true, func() {
		b.WriteRulePos(expr.Pos())
		b.WritelnFieldf("ActionRun = _call%s,", b.FuncName(expr.FuncIx))
		b.WriteFieldf("Inner = ")
		b.WriteExpr(expr.Expr)
	})
}

func writePredicateExpr(
	b *base.Builder,
	kind string,
	funcIx int,
	pos ast.Pos,
	setFuncIx func(int),
) {
	if funcIx == 0 {
		funcIx = b.ExprIndex
		setFuncIx(funcIx)
	}
	writeExprBlock(b, kind, false, func() {
		b.WriteRulePos(pos)
		b.WriteFieldf("PredicateRun = _call%s,", b.FuncName(funcIx))
	})
}

func writeCodeExpr(b *base.Builder, expr *ast.CodeExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	if expr.FuncIx == 0 {
		expr.FuncIx = b.ExprIndex
	}
	writeExprBlock(b, "Code", true, func() {
		b.WriteRulePos(expr.Pos())
		b.WritelnFieldf("ActionRun = _call%s,", b.FuncName(expr.FuncIx))
		if expr.NotSkip {
			b.Writeln("NotSkip = true,")
		}
	})
}

func writeChoiceExpr(b *base.Builder, expr *ast.ChoiceExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	writeExprBlock(b, "Choice", true, func() {
		b.WriteRulePos(expr.Pos())
		b.WriteFieldf("Items = ")
		b.WriteArray("Expr", true, func() {
			for _, alternative := range expr.Alternatives {
				b.WriteExpr(alternative)
			}
		})
	})
}

func writeLabeledExpr(b *base.Builder, expr *ast.LabeledExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	writeExprBlock(b, "Labeled", true, func() {
		b.WriteRulePos(expr.Pos())
		if expr.Label != nil {
			b.Writelnf("Label = %s,", quoteCSharp(expr.Label.Val))
		}
		b.Writef("Inner = ")
		b.WriteExpr(expr.Expr)
		if expr.TextCapture {
			b.Writeln("TextCapture = true,")
		}
	})
}

func writeLiteral(b *base.Builder, expr *ast.LitMatcher) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	value := expr.Val
	if expr.IgnoreCase {
		value = strings.ToLower(value)
	}
	want := strconv.Quote(expr.Val)
	if expr.IgnoreCase {
		want += "i"
	}
	writeExprBlock(b, "Literal", b.SetRulePos, func() {
		b.WriteRulePos(expr.Pos())
		b.WriteFieldf("Value = %s,", quoteCSharp(value))
		if expr.IgnoreCase {
			b.WriteFieldf("IgnoreCase = true,")
		}
		b.WriteFieldf("Want = %s,", quoteCSharp(want))
	})
}

func writeNotExpr(b *base.Builder, expr *ast.NotExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	kind := "Not"
	if expr.Logical {
		kind = "NotLogical"
	}
	writeExprBlock(b, kind, true, func() {
		b.WriteRulePos(expr.Pos())
		b.WriteFieldf("Inner = ")
		b.WriteExpr(expr.Expr)
	})
}

func writeUnaryExpr(b *base.Builder, kind string, pos ast.Pos, inner ast.Expression) {
	writeExprBlock(b, kind, true, func() {
		b.WriteRulePos(pos)
		b.WriteFieldf("Inner = ")
		b.WriteExpr(inner)
	})
}

func writeRecoveryExpr(b *base.Builder, expr *ast.RecoveryExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	writeExprBlock(b, "Recovery", true, func() {
		b.WriteRulePos(expr.Pos())
		b.WriteFieldf("Inner = ")
		b.WriteExpr(expr.Expr)
		b.WriteFieldf("RecoverExpr = ")
		b.WriteExpr(expr.RecoverExpr)
		b.WriteFieldf("FailureLabels = ")
		b.WriteArray("string", true, func() {
			for _, label := range expr.Labels {
				b.WritelnItemf("%s,", quoteCSharp(string(label)))
			}
		})
	})
}

func writeRuleRefExpr(b *base.Builder, expr *ast.RuleRefExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	if b.IRefEnable {
		writeExprBlock(b, "RuleIndexRef", false, func() {
			b.WriteRulePos(expr.Pos())
			info := b.RuleName2Index[expr.Name.Val]
			b.WriteFieldf("Index = %d,", info.Index)
		})
		return
	}
	writeExprBlock(b, "RuleRef", false, func() {
		b.WriteRulePos(expr.Pos())
		b.WriteFieldf("Name = %s,", quoteCSharp(expr.Name.Val))
	})
}

func writeSequenceExpr(b *base.Builder, expr *ast.SeqExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	writeExprBlock(b, "Sequence", true, func() {
		b.WriteRulePos(expr.Pos())
		b.WriteFieldf("Items = ")
		b.WriteArray("Expr", true, func() {
			for _, item := range expr.Exprs {
				b.WriteExpr(item)
			}
		})
	})
}

func writeThrowExpr(b *base.Builder, expr *ast.ThrowExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	writeExprBlock(b, "Throw", true, func() {
		b.WriteRulePos(expr.Pos())
		b.Writelnf("Label = %s,", quoteCSharp(expr.Label))
	})
}

func writeCharClassMatcher(b *base.Builder, expr *ast.CharClassMatcher) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	writeExprBlock(b, "CharClass", true, func() {
		b.WriteRulePos(expr.Pos())
		b.Writelnf("Value = %s,", quoteCSharp(expr.Val))
		if len(expr.Chars) > 0 {
			b.WriteFieldf("Chars = ")
			b.WriteArray("int", false, func() {
				for _, value := range expr.Chars {
					if expr.IgnoreCase {
						value = unicode.ToLower(value)
					}
					b.WriteItemf("%d,", value)
				}
			})
		}
		if len(expr.Ranges) > 0 {
			b.WriteFieldf("Ranges = ")
			b.WriteArray("int", false, func() {
				for _, value := range expr.Ranges {
					if expr.IgnoreCase {
						value = unicode.ToLower(value)
					}
					b.WriteItemf("%d,", value)
				}
			})
		}
		if len(expr.UnicodeClasses) > 0 {
			ranges, err := base.UnicodeRanges(expr.UnicodeClasses)
			if err != nil {
				b.Err = err
				return
			}
			b.WriteFieldf("Classes = ")
			b.WriteArray("UnicodeRange", true, func() {
				for _, item := range ranges {
					b.WritelnItemf("new UnicodeRange(%d, %d, %d),", item.Lo, item.Hi, item.Stride)
				}
			})
		}
		if expr.IgnoreCase {
			b.Writeln("IgnoreCase = true,")
		}
		if expr.Inverted {
			b.Writeln("Inverted = true,")
		}
	})
}

func writeArray(b *base.Builder, typeName string, newline bool, inside func()) {
	prefix := "new List<Expr> {"
	suffix := "},"
	switch typeName {
	case "string":
		prefix = "new List<string> {"
	case "int", "rune":
		prefix = "new int[] {"
	case "UnicodeRange":
		prefix = "new UnicodeRange[] {"
	}
	b.Writef("%s", prefix)
	if newline {
		b.Writeln("")
	}
	b.Indent()
	if inside != nil {
		inside()
	}
	b.Dedent()
	b.Writeln(suffix)
}

func writeFunction(b *base.Builder, funcIx int, code *ast.CodeBlock, funcTpl string) {
	if code == nil {
		return
	}
	value := b.TemplateRender(strings.TrimSpace(code.Val)[1:len(code.Val)-1], true)
	args := base.StringArrayUniq(b.ArgsStack[len(b.ArgsStack)-1])

	var declarations bytes.Buffer
	if len(args) > 0 {
		declarations.WriteString("var stack = p.vstack[^1];\n")
		for _, arg := range args {
			fmt.Fprintf(
				&declarations,
				"object? %s = stack[%s];\n",
				csharpIdentifier(arg),
				quoteCSharp(arg),
			)
		}
	}

	isPredicate := funcTpl == b.CallPredFuncTemplate
	returnType := "object?"
	fallback := "return null;"
	if isPredicate {
		returnType = "bool"
		fallback = "return false;"
	}

	b.Writeln("")
	b.Writelnf("private static %s _call%s(PigeonParser p)", returnType, b.FuncName(funcIx))
	b.Writeln("{")
	b.Indent()
	if declarations.Len() > 0 {
		for _, line := range strings.Split(strings.TrimSuffix(declarations.String(), "\n"), "\n") {
			b.Writeln(line)
		}
	}
	b.Writeln("var c = p.Cur;")
	if value != "" {
		for _, line := range strings.Split(value, "\n") {
			b.Writeln(strings.TrimRight(line, " \t\r"))
		}
	}
	b.Writeln(fallback)
	b.Dedent()
	b.Writeln("}")
}

func csharpIdentifier(value string) string {
	if csharpKeywords[value] {
		return "@" + value
	}
	return value
}

