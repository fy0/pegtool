package builder_cs

import (
	"bytes"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"github.com/fy0/pigeon/bootstrap"
)

func TestGeneratedParserCompilesAndRuns(t *testing.T) {
	dotnet := requireTool(t, "dotnet")
	grammar := `{
{{ if eq .Target "cs" }}
private const string TargetMarker = "cs";
{{ else }}
this branch must not be generated
{{ end }}
}
start = first:word rest:("," word)* !. {
    var values = new List<string> { (string)first! };
    foreach (var item in (List<object?>?)rest ?? new List<object?>()) {
        values.Add((string)((List<object?>)item!)[0]!);
    }
    return string.Join("|", values);
}
word = [\p{L}]+ { return c.Text; }
`

	p := bootstrap.NewParser()
	g, err := p.Parse("grammar.peg", strings.NewReader(grammar))
	if err != nil {
		t.Fatal(err)
	}

	var generated bytes.Buffer
	if err := BuildParser(&generated, g); err != nil {
		t.Fatal(err)
	}

	dir := t.TempDir()
	writeTestFile(t, filepath.Join(dir, "Parser.cs"), generated.Bytes())
	writeTestFile(t, filepath.Join(dir, "Program.cs"), []byte(`
var actual = PigeonParser.Parse("alpha,\u4e16\u754c");
if (!Equals(actual, "alpha|\u4e16\u754c"))
{
    throw new Exception("unexpected parse result: " + actual);
}
Console.WriteLine(actual);
`))
	writeTestFile(t, filepath.Join(dir, "GeneratedParserTest.csproj"), []byte(`
<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <OutputType>Exe</OutputType>
    <TargetFramework>net8.0</TargetFramework>
    <ImplicitUsings>enable</ImplicitUsings>
    <Nullable>enable</Nullable>
  </PropertyGroup>
</Project>
`))

	project := filepath.Join(dir, "GeneratedParserTest.csproj")
	cmd := exec.Command(dotnet, "build", project, "--configuration", "Release", "--nologo", "--verbosity", "quiet")
	cmd.Env = append(os.Environ(),
		"DOTNET_CLI_TELEMETRY_OPTOUT=1",
		"DOTNET_SKIP_FIRST_TIME_EXPERIENCE=1",
		"DOTNET_CLI_WORKLOAD_UPDATE_NOTIFY_DISABLE=true",
	)
	if output, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("dotnet build failed: %v\n%s\nGenerated parser:\n%s", err, output, generated.String())
	}

	dll := filepath.Join(dir, "bin", "Release", "net8.0", "GeneratedParserTest.dll")
	cmd = exec.Command(dotnet, dll)
	if output, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("generated C# parser failed: %v\n%s", err, output)
	} else if strings.TrimSpace(string(output)) != "alpha|\u4e16\u754c" {
		t.Fatalf("unexpected output %q", output)
	}
}

func requireTool(t *testing.T, name string) string {
	t.Helper()
	path, err := exec.LookPath(name)
	if err != nil {
		t.Skipf("%s is not installed", name)
	}
	return path
}

func writeTestFile(t *testing.T, path string, value []byte) {
	t.Helper()
	if err := os.WriteFile(path, value, 0o600); err != nil {
		t.Fatal(err)
	}
}
