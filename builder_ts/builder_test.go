func TestUnicodeClassRangesAreFlatInlineAndDeterministic(t *testing.T) {
	grammar := `
start = letterA / letterB / letterC
letterA = [\p{L}]
letterB = [x\p{L}]
letterC = [\p{L}\p{Mn}]
`
	var first bytes.Buffer
	if err := BuildParser(&first, parseGrammar(t, grammar)); err != nil {
		t.Fatal(err)
	}
	var second bytes.Buffer
	if err := BuildParser(&second, parseGrammar(t, grammar)); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(first.Bytes(), second.Bytes()) {
		t.Fatal("two generations of the same grammar differ")
	}

	generated := first.String()
	if count := strings.Count(generated, "classes: [["); count != 3 {
		t.Fatalf("got %d matcher-local Unicode table groups, want 3", count)
	}
	if count := strings.Count(generated, "65,90,1,"); count != 3 {
		t.Fatalf("got %d copies of the first L range, want one per matcher", count)
	}
	if !strings.Contains(generated, "], [768,879,1,") {
		t.Fatal("a multi-class matcher does not contain separate local tables")
	}
	if strings.Contains(generated, "classes: [\n") {
		t.Fatal("generated Unicode tables contain per-range line overhead")
	}
	for _, fragment := range []string{
		"const unicodeClass",
		"inflateUnicodeTable",
		"{ lo:",
		"hi:",
		"stride:",
	} {
		if strings.Contains(generated, fragment) {
			t.Fatalf("generated parser contains pooled/object range fragment %q", fragment)
		}
	}
	for _, fragment := range []string{
		"let high = table.length / 3 - 1;",
		"const middle = (low + high) >>> 1;",
	} {
		if !strings.Contains(generated, fragment) {
			t.Fatalf("generated parser does not contain binary lookup fragment %q", fragment)
		}
	}
}

func TestUnicodeClassBinarySearchMatchesGo(t *testing.T) {
	for _, name := range []string{"L", "Lu", "Mn", "Other_ID_Start", "White_Space", "Han"} {
		table := unicode.Categories[name]
		if table == nil {
			table = unicode.Properties[name]
		}
		if table == nil {
			table = unicode.Scripts[name]
		}
		if table == nil {
			t.Fatalf("unknown Unicode class %q", name)
		}

		ranges, err := base.UnicodeRanges([]string{name})
		if err != nil {
			t.Fatal(err)
		}
		for current := rune(0); current <= unicode.MaxRune; current++ {
			got := unicodeRangesContain(ranges, current)
			want := unicode.Is(table, current)
			if got != want {
				t.Fatalf("class %s at U+%04X: got %v, want %v", name, current, got, want)
			}
		}
	}
}

func unicodeRangesContain(ranges []base.UnicodeRange, current rune) bool {
	low, high := 0, len(ranges)-1
	for low <= high {
		middle := (low + high) / 2
		item := ranges[middle]
		if current < item.Lo {
			high = middle - 1
		} else if current > item.Hi {
			low = middle + 1
		} else {
			return (current-item.Lo)%item.Stride == 0
		}
	}
	return false
}

func TestGeneratedParserCompilesAndRuns(t *testing.T) {
	tsc := requireTool(t, "tsc")
	node := requireTool(t, "node")

	grammar := `{
{{ if eq .Target "ts" }}
type TargetMarker = string;
{{ else }}
this branch must not be generated
{{ end }}
}
start = first:word rest:("," word)* !. {
  const values: string[] = [first as string];
  for (const item of ((rest ?? []) as any[])) {
    values.push(item[0] as string);
  }
  return values.join("|");
}
word = [\p{L}]+ { return c.text; }
unicodeLetter = [\p{L}] !.
unicodeLetterAgain = [x\p{L}] !.
combiningMark = [\p{Mn}] !.
letterOrMark = [\p{L}\p{Mn}] !.
uppercase = [\p{Lu}] !.
plainChar = [abc] !.
plainRange = [a-c] !.
foldedRange = [a-f]i !.
notLetter = [^\p{L}] !.
`

	g := parseGrammar(t, grammar)

	var generated bytes.Buffer
	if err := BuildParser(&generated, g); err != nil {
		t.Fatal(err)
	}

	dir := t.TempDir()
	parserFile := filepath.Join(dir, "parser.ts")
	runnerFile := filepath.Join(dir, "runner.ts")
	if err := os.WriteFile(parserFile, generated.Bytes(), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(runnerFile, []byte(`
import { parse } from "./parser";
const actual = parse("alpha,\u4e16\u754c");
if (actual !== "alpha|\u4e16\u754c") {
  throw new Error("unexpected parse result: " + String(actual));
}

function expectPass(entrypoint: string, value: string): void {
  parse(value, { entrypoint });
}

function expectFail(entrypoint: string, value: string): void {
  try {
    parse(value, { entrypoint });
  } catch {
    return;
  }
  throw new Error(entrypoint + " unexpectedly accepted " + JSON.stringify(value));
}

expectPass("unicodeLetter", "A");
expectPass("unicodeLetterAgain", "\u4e2d");
expectPass("unicodeLetter", "\u{10400}");
expectPass("combiningMark", "\u0301");
expectPass("letterOrMark", "\u0301");
expectPass("uppercase", "\u0100");
expectPass("plainChar", "b");
expectPass("plainRange", "c");
expectPass("foldedRange", "F");
expectPass("notLetter", "7");
expectFail("unicodeLetter", "7");
expectFail("unicodeLetter", "\uD800");
expectFail("combiningMark", "A");
expectFail("uppercase", "\u0101");
expectFail("plainChar", "d");
expectFail("plainRange", "d");
expectFail("foldedRange", "G");
expectFail("notLetter", "A");
expectFail("notLetter", "");
console.log("ok");
`), 0o600); err != nil {
		t.Fatal(err)
	}

	outDir := filepath.Join(dir, "out")
	cmd := exec.Command(tsc,
		"--strict",
		"--target", "ES2020",
		"--module", "commonjs",
		"--outDir", outDir,
		parserFile,
		runnerFile,
	)
	if output, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("tsc failed: %v\n%s\nGenerated parser:\n%s", err, output, generated.String())
	}

	cmd = exec.Command(node, filepath.Join(outDir, "runner.js"))
	if output, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("node failed: %v\n%s", err, output)
	} else if strings.TrimSpace(string(output)) != "ok" {
		t.Fatalf("unexpected output %q", output)
	}
}

func parseGrammar(t *testing.T, grammar string) *ast.Grammar {
	t.Helper()
	p := bootstrap.NewParser()
	g, err := p.Parse("grammar.peg", strings.NewReader(grammar))
	if err != nil {
		t.Fatal(err)
	}
	return g
}

func requireTool(t *testing.T, name string) string {
	t.Helper()
	path, err := exec.LookPath(name)
	if err != nil {
		t.Skipf("%s is not installed", name)
	}
	return path
}
