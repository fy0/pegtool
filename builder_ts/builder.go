// Package builder_ts generates self-contained TypeScript PEG parsers.
package builder_ts

import (
	"bytes"
	"fmt"
	"io"
	"strconv"
	"strings"
	"unicode"

	"github.com/fy0/pigeon/ast"
	base "github.com/fy0/pigeon/builder"
)

const codeGeneratedComment = "// Code generated by pigeon; DO NOT EDIT.\n"

// BuildParser builds a TypeScript PEG parser and writes it to w.
func BuildParser(w io.Writer, g *ast.Grammar, opts ...base.Option) error {
	b0 := base.Builder{
		W:           w,
		RecvName:    "c",
		Target:      "ts",
		GrammarName: "g",
		IndentUnit:  "  ",
	}
	b := &Builder{Builder: b0}
	b.Init()
	b.SetOptions(opts)
	return b.BuildParser(g)
}

// Builder adapts the shared grammar traversal to TypeScript syntax.
type Builder struct {
	base.Builder
}

func (b *Builder) Init() {
	b.Builder.Init()

	b.Shims.WriteInit = func(b *base.Builder, init *ast.CodeBlock) {
		b.Writeln(codeGeneratedComment)
		if init == nil {
			return
		}
		value := strings.TrimSpace(b.TemplateRender(init.Val[1:len(init.Val)-1], false))
		if value != "" {
			b.Writeln(value)
			b.Writeln("")
		}
	}

	b.Shims.WriteGrammar = func(b *base.Builder, g *ast.Grammar) {
		indexRules(b, g)
		b.Writelnf("export const %s: Grammar = {", b.GrammarName)
		b.Indent()
		b.WritelnFieldf("rules: [")
		b.Indent()
		for _, rule := range g.Rules {
			b.WriteRule(rule)
		}
		b.Dedent()
		b.Writeln("],")
		b.Dedent()
		b.Writeln("};")
		b.Writeln("")
	}

	b.Shims.WriteGrammar2 = b.Shims.WriteGrammar

	b.Shims.WriteActionExpr = func(b *base.Builder, action *ast.ActionExpr) {
		if action == nil {
			b.WriteNilLine()
			return
		}
		if action.FuncIx == 0 {
			action.FuncIx = b.ExprIndex
		}
		b.WriteExprBlock("actionExpr", true, func() {
			b.WriteRulePos(action.Pos())
			b.WritelnFieldf("run: _call%s,", b.FuncName(action.FuncIx))
			b.WriteFieldf("expr: ")
			b.WriteExpr(action.Expr)
		})
	}

	b.Shims.WriteAndCodeExpr = func(b *base.Builder, expr *ast.AndCodeExpr) {
		if expr == nil {
			b.WriteNilLine()
			return
		}
		writePredicateExpr(b, "andCodeExpr", expr.FuncIx, expr.Pos(), func(ix int) {
			expr.FuncIx = ix
		})
	}

	b.Shims.WriteNotCodeExpr = func(b *base.Builder, expr *ast.NotCodeExpr) {
		if expr == nil {
			b.WriteNilLine()
			return
		}
		writePredicateExpr(b, "notCodeExpr", expr.FuncIx, expr.Pos(), func(ix int) {
			expr.FuncIx = ix
		})
	}

	b.Shims.WriteCodeExpr = func(b *base.Builder, expr *ast.CodeExpr) {
		if expr == nil {
			b.WriteNilLine()
			return
		}
		if expr.FuncIx == 0 {
			expr.FuncIx = b.ExprIndex
		}
		b.WriteExprBlock("codeExpr", true, func() {
			b.WriteRulePos(expr.Pos())
			b.WritelnFieldf("run: _call%s,", b.FuncName(expr.FuncIx))
			if expr.NotSkip {
				b.WritelnFieldf("notSkip: true,")
			}
		})
	}

	b.Shims.WriteCharClassMatcher = writeCharClassMatcher

	b.Shims.WriteFunc = writeFunction

	b.Shims.WriteRulePos = func(b *base.Builder, pos ast.Pos) {
		if b.SetRulePos {
			b.WritelnFieldf("pos: { line: %d, col: %d, offset: %d },", pos.Line, pos.Col, pos.Off)
		}
	}

	b.Shims.WriteStaticCodeWrap = func(b *base.Builder) {
		b.WriteStaticCode(runtimeCode)
	}

	b.Shims.WriteNilLine = func(b *base.Builder) {
		b.Writeln("null,")
	}

	b.Shims.WriteExprBlock = func(b *base.Builder, name string, newline bool, inside func()) {
		b.Writef("%s({", name)
		if newline {
			b.Writeln("")
		}
		b.Indent()
		if inside != nil {
			inside()
		}
		b.Dedent()
		b.Writeln("}),")
	}

	b.Shims.WriteArray = func(b *base.Builder, _ string, newline bool, inside func()) {
		b.Writef("[")
		if newline {
			b.Writeln("")
		}
		b.Indent()
		if inside != nil {
			inside()
		}
		b.Dedent()
		b.Writeln("],")
	}
}

func indexRules(b *base.Builder, grammar *ast.Grammar) {
	b.RuleName2Index = make(map[string]*base.ExprInfo, len(grammar.Rules))
	for index, rule := range grammar.Rules {
		info := b.GetExprInfo(rule.Expr)
		info.Index = index
		b.RuleName2Index[rule.Name.Val] = info
	}
}

func writePredicateExpr(
	b *base.Builder,
	name string,
	funcIx int,
	pos ast.Pos,
	setFuncIx func(int),
) {
	if funcIx == 0 {
		funcIx = b.ExprIndex
		setFuncIx(funcIx)
	}
	b.WriteExprBlock(name, false, func() {
		b.WriteRulePos(pos)
		b.WriteFieldf("run: _call%s,", b.FuncName(funcIx))
	})
}

func writeCharClassMatcher(b *base.Builder, expr *ast.CharClassMatcher) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	b.WriteExprBlock("charClassMatcher", true, func() {
		b.WriteRulePos(expr.Pos())
		b.WritelnFieldf("val: %q,", expr.Val)
		if len(expr.Chars) > 0 {
			b.WriteFieldf("chars: ")
			b.WriteArray("number", false, func() {
				for _, value := range expr.Chars {
					if expr.IgnoreCase {
						value = unicode.ToLower(value)
					}
					b.WriteItemf("%d,", value)
				}
			})
		}
		if len(expr.Ranges) > 0 {
			b.WriteFieldf("ranges: ")
			b.WriteArray("number", false, func() {
				for _, value := range expr.Ranges {
					if expr.IgnoreCase {
						value = unicode.ToLower(value)
					}
					b.WriteItemf("%d,", value)
				}
			})
		}
		if len(expr.UnicodeClasses) > 0 {
			ranges, err := base.UnicodeRanges(expr.UnicodeClasses)
			if err != nil {
				b.Err = err
				return
			}
			b.WriteFieldf("classes: ")
			b.WriteArray("number", false, func() {
				for _, item := range ranges {
					b.WriteItemf("%d,%d,%d,", item.Lo, item.Hi, item.Stride)
				}
			})
		}
		if expr.IgnoreCase {
			b.WritelnFieldf("ignoreCase: true,")
		}
		if expr.Inverted {
			b.WritelnFieldf("inverted: true,")
		}
	})
}

func writeFunction(b *base.Builder, funcIx int, code *ast.CodeBlock, funcTpl string) {
	if code == nil {
		return
	}
	value := b.TemplateRender(strings.TrimSpace(code.Val)[1:len(code.Val)-1], true)
	args := base.StringArrayUniq(b.ArgsStack[len(b.ArgsStack)-1])

	var declarations bytes.Buffer
	if len(args) > 0 {
		declarations.WriteString("  const stack = p.vstack[p.vstack.length - 1];\n")
		for _, arg := range args {
			fmt.Fprintf(&declarations, "  const %s: any = stack.get(%s);\n", arg, strconv.Quote(arg))
		}
	}

	isPredicate := funcTpl == b.CallPredFuncTemplate
	returnType := "any"
	fallback := "  return null;\n"
	if isPredicate {
		returnType = "boolean"
		fallback = "  return false;\n"
	}

	b.Writeln("")
	b.Writelnf("function _call%s(p: Parser): %s {", b.FuncName(funcIx), returnType)
	b.Writef("%s", declarations.String())
	b.Writeln("  const c = p.cur;")
	if value != "" {
		for _, line := range strings.Split(value, "\n") {
			b.Writeln("  " + strings.TrimRight(line, " \t\r"))
		}
	}
	b.Writef("%s", fallback)
	b.Writeln("}")
}
