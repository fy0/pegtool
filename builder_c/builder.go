// Package builder_c generates self-contained C99 PEG parsers.
package builder_c

import (
	"fmt"
	"io"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/fy0/pegtool/ast"
	base "github.com/fy0/pegtool/builder"
)

const codeGeneratedComment = "/* Code generated by pegtool; DO NOT EDIT. */"

type callbackSpec struct {
	name      string
	predicate bool
}

// BuildParser builds a C99 PEG parser and writes it to w.
func BuildParser(w io.Writer, g *ast.Grammar, opts ...base.Option) error {
	b0 := base.Builder{
		W:           w,
		RecvName:    "c",
		Target:      "c",
		GrammarName: "g",
		IndentUnit:  "    ",
	}
	b := &Builder{Builder: b0}
	b.Init()
	b.SetOptions(opts)
	if !isCIdentifier(b.RecvName) || cKeywords[b.RecvName] || b.RecvName == "p" {
		return fmt.Errorf("invalid C receiver name %q", b.RecvName)
	}
	b.collectCallbacks(g)
	return b.BuildParser(g)
}

// Builder adapts the shared grammar traversal to C99 syntax.
type Builder struct {
	base.Builder
	callbacks  []callbackSpec
	useCaseMap bool
}

func (b *Builder) Init() {
	b.Builder.Init()

	b.Shims.WriteInit = func(bb *base.Builder, init *ast.CodeBlock) {
		bb.Writeln(codeGeneratedComment)
		bb.Writeln(strings.TrimSpace(runtimePreamble))
		bb.Writeln("")
		writeCaseMap(bb, b.useCaseMap)
		bb.Writeln("")
		bb.Writeln(strings.TrimSpace(runtimeCore))
		bb.Writeln("")
		for _, callback := range b.callbacks {
			returnType := "PegtoolValue"
			if callback.predicate {
				returnType = "int"
			}
			bb.Writelnf("static %s %s(PegtoolParser *p);", returnType, callback.name)
		}
		if len(b.callbacks) > 0 {
			bb.Writeln("")
		}
		if init == nil {
			return
		}
		value := strings.TrimSpace(bb.TemplateRender(init.Val[1:len(init.Val)-1], false))
		if value != "" {
			bb.Writeln(value)
			bb.Writeln("")
		}
	}

	b.Shims.WriteGrammar = func(bb *base.Builder, grammar *ast.Grammar) {
		indexRules(bb, grammar)
		bb.Writeln("static const PegtoolRule _pegtool_rules[] = {")
		bb.Indent()
		for _, rule := range grammar.Rules {
			bb.WriteRule(rule)
		}
		bb.Dedent()
		bb.Writeln("};")
		bb.Writelnf(
			"static const PegtoolGrammar %s = { _pegtool_rules, sizeof(_pegtool_rules) / sizeof(_pegtool_rules[0]) };",
			bb.GrammarName,
		)
		bb.Writeln("")
	}
	b.Shims.WriteGrammar2 = b.Shims.WriteGrammar
	b.Shims.WriteRule = writeRule
	b.Shims.WriteAndExpr = writeAndExpr
	b.Shims.WriteAnyMatcher = func(bb *base.Builder, expr *ast.AnyMatcher) {
		if expr == nil {
			bb.WriteNilLine()
			return
		}
		writeExprBlock(bb, "PEGTOOL_EXPR_ANY", false, func() { bb.WriteRulePos(expr.Pos()) })
	}
	b.Shims.WriteActionExpr = writeActionExpr
	b.Shims.WriteAndCodeExpr = func(bb *base.Builder, expr *ast.AndCodeExpr) {
		if expr == nil {
			bb.WriteNilLine()
			return
		}
		writePredicateExpr(bb, "PEGTOOL_EXPR_AND_CODE", expr.FuncIx, expr.Pos(), func(ix int) {
			expr.FuncIx = ix
		})
	}
	b.Shims.WriteCharClassMatcher = writeCharClassMatcher
	b.Shims.WriteCodeExpr = writeCodeExpr
	b.Shims.WriteChoiceExpr = func(bb *base.Builder, expr *ast.ChoiceExpr) {
		if expr == nil {
			bb.WriteNilLine()
			return
		}
		writeExprList(bb, "PEGTOOL_EXPR_CHOICE", expr.Pos(), expr.Alternatives)
	}
	b.Shims.WriteLabeledExpr = writeLabeledExpr
	b.Shims.WriteLitMatcher = writeLiteral
	b.Shims.WriteNotCodeExpr = func(bb *base.Builder, expr *ast.NotCodeExpr) {
		if expr == nil {
			bb.WriteNilLine()
			return
		}
		writePredicateExpr(bb, "PEGTOOL_EXPR_NOT_CODE", expr.FuncIx, expr.Pos(), func(ix int) {
			expr.FuncIx = ix
		})
	}
	b.Shims.WriteNotExpr = writeNotExpr
	b.Shims.WriteOneOrMoreExpr = func(bb *base.Builder, expr *ast.OneOrMoreExpr) {
		if expr == nil {
			bb.WriteNilLine()
			return
		}
		writeUnaryExpr(bb, "PEGTOOL_EXPR_ONE_OR_MORE", expr.Pos(), expr.Expr)
	}
	b.Shims.WriteRecoveryExpr = writeRecoveryExpr
	b.Shims.WriteRuleRefExpr = writeRuleRefExpr
	b.Shims.WriteSeqExpr = func(bb *base.Builder, expr *ast.SeqExpr) {
		if expr == nil {
			bb.WriteNilLine()
			return
		}
		writeExprList(bb, "PEGTOOL_EXPR_SEQUENCE", expr.Pos(), expr.Exprs)
	}
	b.Shims.WriteThrowExpr = writeThrowExpr
	b.Shims.WriteZeroOrMoreExpr = func(bb *base.Builder, expr *ast.ZeroOrMoreExpr) {
		if expr == nil {
			bb.WriteNilLine()
			return
		}
		writeUnaryExpr(bb, "PEGTOOL_EXPR_ZERO_OR_MORE", expr.Pos(), expr.Expr)
	}
	b.Shims.WriteZeroOrOneExpr = func(bb *base.Builder, expr *ast.ZeroOrOneExpr) {
		if expr == nil {
			bb.WriteNilLine()
			return
		}
		writeUnaryExpr(bb, "PEGTOOL_EXPR_ZERO_OR_ONE", expr.Pos(), expr.Expr)
	}
	b.Shims.WriteFunc = writeFunction
	b.Shims.WriteRulePos = func(bb *base.Builder, pos ast.Pos) {
		if bb.SetRulePos {
			bb.WritelnFieldf(".pos = { %d, %d, %d },", pos.Line, pos.Col, pos.Off)
		}
	}
	b.Shims.WriteStaticCodeWrap = func(bb *base.Builder) { bb.WriteStaticCode(runtimeFooter) }
	b.Shims.WriteNilLine = func(bb *base.Builder) { bb.Writeln("NULL,") }
	b.Shims.WriteExprBlock = func(bb *base.Builder, name string, newline bool, inside func()) {
		writeExprBlock(bb, name, newline, inside)
	}
	b.Shims.WriteArray = func(bb *base.Builder, typeName string, newline bool, inside func()) {
		bb.Writef("(const %s[]){", typeName)
		if newline {
			bb.Writeln("")
		}
		bb.Indent()
		if inside != nil {
			inside()
		}
		bb.Dedent()
		bb.Writeln("},")
	}
}

func (b *Builder) collectCallbacks(grammar *ast.Grammar) {
	b.callbacks = nil
	b.useCaseMap = false
	for _, rule := range grammar.Rules {
		if rule == nil || rule.Name == nil {
			continue
		}
		index := 0
		b.RuleName = rule.Name.Val
		b.collectExprCallbacks(rule.Expr, &index)
	}
}

func (b *Builder) collectExprCallbacks(expr ast.Expression, index *int) {
	if expr == nil {
		return
	}
	(*index)++
	current := *index
	add := func(predicate bool, setIndex func(int)) {
		setIndex(current)
		b.callbacks = append(b.callbacks, callbackSpec{name: b.FuncName(current), predicate: predicate})
	}

	switch expr := expr.(type) {
	case *ast.ActionExpr:
		add(false, func(value int) { expr.FuncIx = value })
		b.collectExprCallbacks(expr.Expr, index)
	case *ast.AndCodeExpr:
		add(true, func(value int) { expr.FuncIx = value })
	case *ast.AndExpr:
		b.collectExprCallbacks(expr.Expr, index)
	case *ast.CharClassMatcher:
		b.useCaseMap = b.useCaseMap || expr.IgnoreCase
	case *ast.LitMatcher:
		b.useCaseMap = b.useCaseMap || expr.IgnoreCase
	case *ast.AnyMatcher, *ast.RuleRefExpr, *ast.ThrowExpr:
	case *ast.ChoiceExpr:
		for _, child := range expr.Alternatives {
			b.collectExprCallbacks(child, index)
		}
	case *ast.CodeExpr:
		add(false, func(value int) { expr.FuncIx = value })
	case *ast.LabeledExpr:
		b.collectExprCallbacks(expr.Expr, index)
	case *ast.NotCodeExpr:
		add(true, func(value int) { expr.FuncIx = value })
	case *ast.NotExpr:
		b.collectExprCallbacks(expr.Expr, index)
	case *ast.OneOrMoreExpr:
		b.collectExprCallbacks(expr.Expr, index)
	case *ast.RecoveryExpr:
		b.collectExprCallbacks(expr.Expr, index)
		b.collectExprCallbacks(expr.RecoverExpr, index)
	case *ast.SeqExpr:
		for _, child := range expr.Exprs {
			b.collectExprCallbacks(child, index)
		}
	case *ast.ZeroOrMoreExpr:
		b.collectExprCallbacks(expr.Expr, index)
	case *ast.ZeroOrOneExpr:
		b.collectExprCallbacks(expr.Expr, index)
	}
}

func indexRules(b *base.Builder, grammar *ast.Grammar) {
	b.RuleName2Index = make(map[string]*base.ExprInfo, len(grammar.Rules))
	for index, rule := range grammar.Rules {
		info := b.GetExprInfo(rule.Expr)
		info.Index = index
		b.RuleName2Index[rule.Name.Val] = info
	}
}

func writeRule(b *base.Builder, rule *ast.Rule) {
	if rule == nil || rule.Name == nil {
		return
	}
	b.ExprIndex = 0
	b.RuleName = rule.Name.Val
	if b.Entrypoint == "" {
		b.Entrypoint = rule.Name.Val
	}
	b.Writeln("{")
	b.Indent()
	b.Writelnf(".name = %s,", quoteC(rule.Name.Val))
	if rule.DisplayName != nil && rule.DisplayName.Val != "" {
		b.Writelnf(".display_name = %s,", quoteC(rule.DisplayName.Val))
	}
	if rule.IsLabelExists {
		b.Writeln(".var_exists = 1,")
	}
	b.WriteRulePos(rule.Pos())
	b.Writef(".expr = ")
	b.WriteExpr(rule.Expr)
	b.Writeln(".reserved = 0,")
	b.Dedent()
	b.Writeln("},")
}

func writeExprBlock(b *base.Builder, kind string, newline bool, inside func()) {
	b.Writef("&(const PegtoolExpr){ .kind = %s,", kind)
	if newline {
		b.Writeln("")
	}
	b.Indent()
	if inside != nil {
		inside()
	}
	b.Writeln(".reserved = 0,")
	b.Dedent()
	b.Writeln("},")
}

func writeAndExpr(b *base.Builder, expr *ast.AndExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	kind := "PEGTOOL_EXPR_AND"
	if expr.Logical {
		kind = "PEGTOOL_EXPR_AND_LOGICAL"
	}
	writeUnaryExpr(b, kind, expr.Pos(), expr.Expr)
}

func writeNotExpr(b *base.Builder, expr *ast.NotExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	kind := "PEGTOOL_EXPR_NOT"
	if expr.Logical {
		kind = "PEGTOOL_EXPR_NOT_LOGICAL"
	}
	writeUnaryExpr(b, kind, expr.Pos(), expr.Expr)
}

func writeUnaryExpr(b *base.Builder, kind string, pos ast.Pos, inner ast.Expression) {
	writeExprBlock(b, kind, true, func() {
		b.WriteRulePos(pos)
		b.Writef(".inner = ")
		b.WriteExpr(inner)
	})
}

func writeActionExpr(b *base.Builder, expr *ast.ActionExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	if expr.FuncIx == 0 {
		expr.FuncIx = b.ExprIndex
	}
	writeExprBlock(b, "PEGTOOL_EXPR_ACTION", true, func() {
		b.WriteRulePos(expr.Pos())
		b.Writelnf(".action = %s,", b.FuncName(expr.FuncIx))
		b.Writef(".inner = ")
		b.WriteExpr(expr.Expr)
	})
}

func writePredicateExpr(
	b *base.Builder,
	kind string,
	funcIx int,
	pos ast.Pos,
	setFuncIx func(int),
) {
	if funcIx == 0 {
		funcIx = b.ExprIndex
		setFuncIx(funcIx)
	}
	writeExprBlock(b, kind, false, func() {
		b.WriteRulePos(pos)
		b.WriteFieldf(".predicate = %s,", b.FuncName(funcIx))
	})
}

func writeCodeExpr(b *base.Builder, expr *ast.CodeExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	if expr.FuncIx == 0 {
		expr.FuncIx = b.ExprIndex
	}
	writeExprBlock(b, "PEGTOOL_EXPR_CODE", true, func() {
		b.WriteRulePos(expr.Pos())
		b.Writelnf(".action = %s,", b.FuncName(expr.FuncIx))
		if expr.NotSkip {
			b.Writeln(".not_skip = 1,")
		}
	})
}

func writeExprList(b *base.Builder, kind string, pos ast.Pos, values []ast.Expression) {
	writeExprBlock(b, kind, true, func() {
		b.WriteRulePos(pos)
		if len(values) == 0 {
			return
		}
		b.Writeln(".items = (const PegtoolExpr *const[]){")
		b.Indent()
		for _, value := range values {
			b.WriteExpr(value)
		}
		b.Dedent()
		b.Writeln("},")
		b.Writelnf(".item_count = %d,", len(values))
	})
}

func writeLabeledExpr(b *base.Builder, expr *ast.LabeledExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	writeExprBlock(b, "PEGTOOL_EXPR_LABELED", true, func() {
		b.WriteRulePos(expr.Pos())
		if expr.Label != nil && expr.Label.Val != "" {
			b.Writelnf(".label = %s,", quoteC(expr.Label.Val))
		}
		if expr.TextCapture {
			b.Writeln(".text_capture = 1,")
		}
		b.Writef(".inner = ")
		b.WriteExpr(expr.Expr)
	})
}

func writeLiteral(b *base.Builder, expr *ast.LitMatcher) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	runes := []rune(expr.Val)
	if expr.IgnoreCase {
		for index, value := range runes {
			runes[index] = unicode.ToLower(value)
		}
	}
	writeExprBlock(b, "PEGTOOL_EXPR_LITERAL", true, func() {
		b.WriteRulePos(expr.Pos())
		if len(runes) > 0 {
			b.Writef(".runes = (const uint32_t[]){")
			for _, value := range runes {
				b.Writef(" 0x%X,", value)
			}
			b.Writeln(" },")
		}
		b.Writelnf(".rune_count = %d,", len(runes))
		ignoreCaseFlag := ""
		if expr.IgnoreCase {
			ignoreCaseFlag = "i"
			b.Writeln(".ignore_case = 1,")
		}
		b.Writelnf(".want = %s,", quoteC(strconv.Quote(expr.Val)+ignoreCaseFlag))
	})
}

func writeCharClassMatcher(b *base.Builder, expr *ast.CharClassMatcher) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	writeExprBlock(b, "PEGTOOL_EXPR_CHAR_CLASS", true, func() {
		b.WriteRulePos(expr.Pos())
		b.Writelnf(".value = %s,", quoteC(expr.Val))
		writeRunes := func(field string, values []rune) {
			if len(values) == 0 {
				return
			}
			b.Writef(".%s = (const uint32_t[]){", field)
			for _, value := range values {
				if expr.IgnoreCase {
					value = unicode.ToLower(value)
				}
				b.Writef(" 0x%X,", value)
			}
			b.Writeln(" },")
			b.Writelnf(".%s_count = %d,", field, len(values))
		}
		writeRunes("chars", expr.Chars)
		writeRunes("ranges", expr.Ranges)
		if len(expr.UnicodeClasses) > 0 {
			ranges, err := base.UnicodeRanges(expr.UnicodeClasses)
			if err != nil {
				b.Err = err
				return
			}
			b.Writeln(".classes = (const PegtoolUnicodeRange[]){")
			b.Indent()
			for _, item := range ranges {
				b.Writelnf("{ 0x%X, 0x%X, %d },", item.Lo, item.Hi, item.Stride)
			}
			b.Dedent()
			b.Writeln("},")
			b.Writelnf(".class_count = %d,", len(ranges))
		}
		if expr.IgnoreCase {
			b.Writeln(".ignore_case = 1,")
		}
		if expr.Inverted {
			b.Writeln(".inverted = 1,")
		}
	})
}

func writeRecoveryExpr(b *base.Builder, expr *ast.RecoveryExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	writeExprBlock(b, "PEGTOOL_EXPR_RECOVERY", true, func() {
		b.WriteRulePos(expr.Pos())
		b.Writef(".inner = ")
		b.WriteExpr(expr.Expr)
		b.Writef(".recover_expr = ")
		b.WriteExpr(expr.RecoverExpr)
		if len(expr.Labels) > 0 {
			b.Writef(".failure_labels = (const char *const[]){")
			for _, label := range expr.Labels {
				b.Writef(" %s,", quoteC(string(label)))
			}
			b.Writeln(" },")
			b.Writelnf(".failure_label_count = %d,", len(expr.Labels))
		}
	})
}

func writeRuleRefExpr(b *base.Builder, expr *ast.RuleRefExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	if b.IRefEnable {
		writeExprBlock(b, "PEGTOOL_EXPR_RULE_INDEX", false, func() {
			b.WriteRulePos(expr.Pos())
			if expr.Name != nil && expr.Name.Val != "" {
				b.WriteFieldf(".index = %d,", b.RuleName2Index[expr.Name.Val].Index)
			}
		})
		return
	}
	writeExprBlock(b, "PEGTOOL_EXPR_RULE_REF", false, func() {
		b.WriteRulePos(expr.Pos())
		if expr.Name != nil && expr.Name.Val != "" {
			b.WriteFieldf(".name = %s,", quoteC(expr.Name.Val))
		}
	})
}

func writeThrowExpr(b *base.Builder, expr *ast.ThrowExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	writeExprBlock(b, "PEGTOOL_EXPR_THROW", false, func() {
		b.WriteRulePos(expr.Pos())
		b.WriteFieldf(".label = %s,", quoteC(expr.Label))
	})
}

func writeFunction(b *base.Builder, funcIx int, code *ast.CodeBlock, funcTpl string) {
	if code == nil {
		return
	}
	trimmed := strings.TrimSpace(code.Val)
	value := b.TemplateRender(trimmed[1:len(trimmed)-1], true)
	args := base.StringArrayUniq(b.ArgsStack[len(b.ArgsStack)-1])
	isPredicate := funcTpl == b.CallPredFuncTemplate
	returnType := "PegtoolValue"
	fallback := "return pegtool_value_null();"
	if isPredicate {
		returnType = "int"
		fallback = "return 0;"
	}

	b.Writeln("")
	b.Writelnf("static %s %s(PegtoolParser *p) {", returnType, b.FuncName(funcIx))
	b.Indent()
	for _, arg := range args {
		identifier := cLabelIdentifier(arg, b.RecvName)
		b.Writelnf("const PegtoolValue *%s = pegtool_parser_label(p, %s);", identifier, quoteC(arg))
		b.Writelnf("(void)%s;", identifier)
	}
	b.Writelnf("PegtoolCurrent *%s = &p->cur;", b.RecvName)
	b.Writeln("(void)p;")
	b.Writelnf("(void)%s;", b.RecvName)
	if value != "" {
		for _, line := range strings.Split(value, "\n") {
			b.Writeln(strings.TrimRight(line, " \t\r"))
		}
	}
	b.Writeln(fallback)
	b.Dedent()
	b.Writeln("}")
}

func writeCaseMap(b *base.Builder, enabled bool) {
	b.Writeln("static const PegtoolCaseMap _pegtool_case_map[] = {")
	b.Indent()
	count := 0
	if enabled {
		for value := rune(0); value <= utf8.MaxRune; value++ {
			lower := unicode.ToLower(value)
			if lower != value {
				b.Writelnf("{ 0x%X, 0x%X },", value, lower)
				count++
			}
		}
	} else {
		b.Writeln("{ 0, 0 },")
	}
	b.Dedent()
	b.Writeln("};")
	b.Writelnf("static const size_t _pegtool_case_map_count = %d;", count)
}

func sanitizeIdentifier(value string) string {
	var out strings.Builder
	for index, r := range value {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || r == '_' || (index > 0 && r >= '0' && r <= '9') {
			out.WriteRune(r)
		} else {
			fmt.Fprintf(&out, "_%X", r)
		}
	}
	return out.String()
}

func cLabelIdentifier(value, receiver string) string {
	if !cKeywords[value] && value != "p" && value != receiver {
		return value
	}
	return "_pegtool_label_" + sanitizeIdentifier(value)
}

func isCIdentifier(value string) bool {
	if value == "" {
		return false
	}
	for index, current := range value {
		if (current >= 'a' && current <= 'z') || (current >= 'A' && current <= 'Z') || current == '_' {
			continue
		}
		if index > 0 && current >= '0' && current <= '9' {
			continue
		}
		return false
	}
	return true
}

var cKeywords = map[string]bool{
	"auto": true, "break": true, "case": true, "char": true,
	"const": true, "continue": true, "default": true, "do": true,
	"double": true, "else": true, "enum": true, "extern": true,
	"float": true, "for": true, "goto": true, "if": true,
	"inline": true, "int": true, "long": true, "register": true,
	"restrict": true, "return": true, "short": true, "signed": true,
	"sizeof": true, "static": true, "struct": true, "switch": true,
	"typedef": true, "union": true, "unsigned": true, "void": true,
	"volatile": true, "while": true, "_Bool": true, "_Complex": true,
	"_Imaginary": true,
}

func quoteC(value string) string {
	var out strings.Builder
	out.WriteByte('"')
	for _, current := range []byte(value) {
		switch current {
		case '\\':
			out.WriteString(`\\`)
		case '"':
			out.WriteString(`\"`)
		case '\n':
			out.WriteString(`\n`)
		case '\r':
			out.WriteString(`\r`)
		case '\t':
			out.WriteString(`\t`)
		default:
			if current >= 0x20 && current <= 0x7e {
				out.WriteByte(current)
			} else {
				fmt.Fprintf(&out, `\%03o`, current)
			}
		}
	}
	out.WriteByte('"')
	return out.String()
}
