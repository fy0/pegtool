// Package builder_rust generates self-contained Rust PEG parsers.
package builder_rust

import (
	"bytes"
	"fmt"
	"io"
	"strings"
	"unicode"

	"github.com/fy0/pigeon/ast"
	base "github.com/fy0/pigeon/builder"
)

const codeGeneratedComment = "// Code generated by pigeon; DO NOT EDIT."

// BuildParser builds a Rust PEG parser and writes it to w.
func BuildParser(w io.Writer, g *ast.Grammar, opts ...base.Option) error {
	b0 := base.Builder{
		W:           w,
		RecvName:    "c",
		Target:      "rust",
		GrammarName: "g",
		IndentUnit:  "    ",
	}
	b := &Builder{Builder: b0}
	b.Init()
	b.SetOptions(opts)
	return b.BuildParser(g)
}

// Builder adapts the shared grammar traversal to Rust syntax.
type Builder struct {
	base.Builder
	implClosed bool
}

func (b *Builder) Init() {
	b.Builder.Init()

	b.Shims.WriteInit = func(out *base.Builder, init *ast.CodeBlock) {
		out.Writeln(codeGeneratedComment)
		out.Writeln("#![allow(dead_code, non_snake_case, unreachable_code, unused_variables)]")
		out.Writeln("use std::any::Any;")
		out.Writeln("use std::cell::RefCell;")
		out.Writeln("use std::collections::{BTreeMap, HashMap};")
		out.Writeln("use std::error::Error;")
		out.Writeln("use std::fmt;")
		out.Writeln("use std::rc::Rc;")
		out.Writeln("")
		if init != nil {
			value := strings.TrimSpace(out.TemplateRender(init.Val[1:len(init.Val)-1], false))
			if value != "" {
				out.Writeln(value)
				out.Writeln("")
			}
		}
		out.Writeln("impl PigeonParser {")
		out.Indent()
	}

	b.Shims.WriteGrammar = func(out *base.Builder, grammar *ast.Grammar) {
		indexRules(out, grammar)
		out.Writelnf("fn %s() -> Grammar {", out.GrammarName)
		out.Indent()
		out.Writeln("Grammar {")
		out.Indent()
		out.Writeln("rules: vec![")
		out.Indent()
		for _, rule := range grammar.Rules {
			out.WriteRule(rule)
		}
		out.Dedent()
		out.Writeln("],")
		out.Dedent()
		out.Writeln("}")
		out.Dedent()
		out.Writeln("}")
		out.Writeln("")
	}
	b.Shims.WriteGrammar2 = b.Shims.WriteGrammar

	b.Shims.WriteRule = writeRule
	b.Shims.WriteAndExpr = writeAndExpr
	b.Shims.WriteAnyMatcher = func(out *base.Builder, expr *ast.AnyMatcher) {
		if expr == nil {
			out.WriteNilLine()
			return
		}
		out.Writeln("Expr::any(),")
	}
	b.Shims.WriteActionExpr = writeActionExpr
	b.Shims.WriteAndCodeExpr = func(out *base.Builder, expr *ast.AndCodeExpr) {
		if expr == nil {
			out.WriteNilLine()
			return
		}
		writePredicateExpr(out, "AndCode", expr.FuncIx, func(ix int) { expr.FuncIx = ix })
	}
	b.Shims.WriteCharClassMatcher = writeCharClassMatcher
	b.Shims.WriteCodeExpr = writeCodeExpr
	b.Shims.WriteChoiceExpr = func(out *base.Builder, expr *ast.ChoiceExpr) {
		if expr == nil {
			out.WriteNilLine()
			return
		}
		writeExprList(out, "choice", expr.Alternatives)
	}
	b.Shims.WriteLabeledExpr = writeLabeledExpr
	b.Shims.WriteLitMatcher = writeLiteral
	b.Shims.WriteNotCodeExpr = func(out *base.Builder, expr *ast.NotCodeExpr) {
		if expr == nil {
			out.WriteNilLine()
			return
		}
		writePredicateExpr(out, "NotCode", expr.FuncIx, func(ix int) { expr.FuncIx = ix })
	}
	b.Shims.WriteNotExpr = writeNotExpr
	b.Shims.WriteOneOrMoreExpr = func(out *base.Builder, expr *ast.OneOrMoreExpr) {
		if expr == nil {
			out.WriteNilLine()
			return
		}
		writeUnaryExpr(out, "OneOrMore", expr.Expr)
	}
	b.Shims.WriteRecoveryExpr = writeRecoveryExpr
	b.Shims.WriteRuleRefExpr = writeRuleRefExpr
	b.Shims.WriteSeqExpr = func(out *base.Builder, expr *ast.SeqExpr) {
		if expr == nil {
			out.WriteNilLine()
			return
		}
		writeExprList(out, "sequence", expr.Exprs)
	}
	b.Shims.WriteThrowExpr = writeThrowExpr
	b.Shims.WriteZeroOrMoreExpr = func(out *base.Builder, expr *ast.ZeroOrMoreExpr) {
		if expr == nil {
			out.WriteNilLine()
			return
		}
		writeUnaryExpr(out, "ZeroOrMore", expr.Expr)
	}
	b.Shims.WriteZeroOrOneExpr = func(out *base.Builder, expr *ast.ZeroOrOneExpr) {
		if expr == nil {
			out.WriteNilLine()
			return
		}
		writeUnaryExpr(out, "ZeroOrOne", expr.Expr)
	}
	b.Shims.WriteFunc = writeFunction
	b.Shims.WriteRulePos = func(_ *base.Builder, _ ast.Pos) {}
	b.Shims.WriteNilLine = func(out *base.Builder) { out.Writeln("Expr::invalid(),") }
	b.Shims.WriteExprBlock = func(out *base.Builder, name string, _ bool, inside func()) {
		out.Writelnf("Expr::custom(ExprKind::%s,", strings.ToUpper(name[:1])+name[1:])
		out.Indent()
		if inside != nil {
			inside()
		}
		out.Dedent()
		out.Writeln("),")
	}
	b.Shims.WriteArray = func(out *base.Builder, _ string, newline bool, inside func()) {
		out.Writef("vec![")
		if newline {
			out.Writeln("")
		}
		out.Indent()
		if inside != nil {
			inside()
		}
		out.Dedent()
		out.Writeln("],")
	}
	b.Shims.WriteStaticCodeWrap = func(out *base.Builder) {
		out.Dedent()
		out.Writeln("}")
		out.Writeln("")
		b.implClosed = true
		out.WriteStaticCode(runtimeCode)
	}
	b.Shims.WriteFooter = func(out *base.Builder) {
		if b.implClosed {
			return
		}
		out.Dedent()
		out.Writeln("}")
		b.implClosed = true
	}
}

func indexRules(b *base.Builder, grammar *ast.Grammar) {
	b.RuleName2Index = make(map[string]*base.ExprInfo, len(grammar.Rules))
	for index, rule := range grammar.Rules {
		info := b.GetExprInfo(rule.Expr)
		info.Index = index
		b.RuleName2Index[rule.Name.Val] = info
	}
}

func writeRule(b *base.Builder, rule *ast.Rule) {
	if rule == nil || rule.Name == nil {
		return
	}
	b.ExprIndex = 0
	b.RuleName = rule.Name.Val
	if b.Entrypoint == "" {
		b.Entrypoint = rule.Name.Val
	}
	displayName := "None"
	if rule.DisplayName != nil && rule.DisplayName.Val != "" {
		displayName = "Some(" + quoteRust(rule.DisplayName.Val) + ")"
	}
	b.Writeln("Rule::new(")
	b.Indent()
	b.Writelnf("%s,", quoteRust(rule.Name.Val))
	b.Writelnf("%s,", displayName)
	b.Writelnf("%t,", rule.IsLabelExists)
	b.WriteExpr(rule.Expr)
	b.Dedent()
	b.Writeln("),")
}

func writeActionExpr(b *base.Builder, expr *ast.ActionExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	if expr.FuncIx == 0 {
		expr.FuncIx = b.ExprIndex
	}
	b.Writeln("Expr::action(")
	b.Indent()
	b.Writelnf("Self::_call%s,", b.FuncName(expr.FuncIx))
	b.WriteExpr(expr.Expr)
	b.Dedent()
	b.Writeln("),")
}

func writePredicateExpr(b *base.Builder, kind string, funcIx int, setFuncIx func(int)) {
	if funcIx == 0 {
		funcIx = b.ExprIndex
		setFuncIx(funcIx)
	}
	b.Writelnf("Expr::predicate(ExprKind::%s, Self::_call%s),", kind, b.FuncName(funcIx))
}

func writeCodeExpr(b *base.Builder, expr *ast.CodeExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	if expr.FuncIx == 0 {
		expr.FuncIx = b.ExprIndex
	}
	b.Writelnf("Expr::code(Self::_call%s, %t),", b.FuncName(expr.FuncIx), expr.NotSkip)
}

func writeAndExpr(b *base.Builder, expr *ast.AndExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	kind := "And"
	if expr.Logical {
		kind = "AndLogical"
	}
	writeUnaryExpr(b, kind, expr.Expr)
}

func writeNotExpr(b *base.Builder, expr *ast.NotExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	kind := "Not"
	if expr.Logical {
		kind = "NotLogical"
	}
	writeUnaryExpr(b, kind, expr.Expr)
}

func writeUnaryExpr(b *base.Builder, kind string, inner ast.Expression) {
	b.Writelnf("Expr::unary(ExprKind::%s,", kind)
	b.Indent()
	b.WriteExpr(inner)
	b.Dedent()
	b.Writeln("),")
}

func writeExprList(b *base.Builder, constructor string, values []ast.Expression) {
	b.Writelnf("Expr::%s(vec![", constructor)
	b.Indent()
	for _, value := range values {
		b.WriteExpr(value)
	}
	b.Dedent()
	b.Writeln("]),")
}

func writeLabeledExpr(b *base.Builder, expr *ast.LabeledExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	label := ""
	if expr.Label != nil {
		label = expr.Label.Val
	}
	b.Writelnf("Expr::labeled(%s, %t,", quoteRust(label), expr.TextCapture)
	b.Indent()
	b.WriteExpr(expr.Expr)
	b.Dedent()
	b.Writeln("),")
}

func writeLiteral(b *base.Builder, expr *ast.LitMatcher) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	value := expr.Val
	if expr.IgnoreCase {
		value = strings.ToLower(value)
	}
	want := fmt.Sprintf("%q", expr.Val)
	if expr.IgnoreCase {
		want += "i"
	}
	b.Writelnf(
		"Expr::literal(%s, %s, %t),",
		quoteRust(value),
		quoteRust(want),
		expr.IgnoreCase,
	)
}

func writeRuleRefExpr(b *base.Builder, expr *ast.RuleRefExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	if b.IRefEnable {
		info := b.RuleName2Index[expr.Name.Val]
		b.Writelnf("Expr::rule_index_ref(%d),", info.Index)
		return
	}
	b.Writelnf("Expr::rule_ref(%s),", quoteRust(expr.Name.Val))
}

func writeRecoveryExpr(b *base.Builder, expr *ast.RecoveryExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	b.Writeln("Expr::recovery(")
	b.Indent()
	b.WriteExpr(expr.Expr)
	b.WriteExpr(expr.RecoverExpr)
	b.Writeln("vec![")
	b.Indent()
	for _, label := range expr.Labels {
		b.Writelnf("%s.to_string(),", quoteRust(string(label)))
	}
	b.Dedent()
	b.Writeln("],")
	b.Dedent()
	b.Writeln("),")
}

func writeThrowExpr(b *base.Builder, expr *ast.ThrowExpr) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	b.Writelnf("Expr::throw(%s),", quoteRust(expr.Label))
}

func writeCharClassMatcher(b *base.Builder, expr *ast.CharClassMatcher) {
	if expr == nil {
		b.WriteNilLine()
		return
	}
	ranges, err := base.UnicodeRanges(expr.UnicodeClasses)
	if err != nil {
		b.Err = err
		return
	}
	b.Writeln("Expr::char_class(")
	b.Indent()
	b.Writelnf("%s,", quoteRust(expr.Val))
	writeRuneVector(b, expr.Chars, expr.IgnoreCase)
	writeRuneVector(b, expr.Ranges, expr.IgnoreCase)
	b.Writeln("vec![")
	b.Indent()
	for _, item := range ranges {
		b.Writelnf("UnicodeRange::new(%d, %d, %d),", item.Lo, item.Hi, item.Stride)
	}
	b.Dedent()
	b.Writeln("],")
	b.Writelnf("%t,", expr.IgnoreCase)
	b.Writelnf("%t,", expr.Inverted)
	b.Dedent()
	b.Writeln("),")
}

func writeRuneVector(b *base.Builder, values []rune, ignoreCase bool) {
	b.Writeln("vec![")
	b.Indent()
	for _, value := range values {
		if ignoreCase {
			value = unicode.ToLower(value)
		}
		b.Writelnf("%d,", value)
	}
	b.Dedent()
	b.Writeln("],")
}

func writeFunction(b *base.Builder, funcIx int, code *ast.CodeBlock, funcTpl string) {
	if code == nil {
		return
	}
	value := b.TemplateRender(strings.TrimSpace(code.Val)[1:len(code.Val)-1], true)
	args := base.StringArrayUniq(b.ArgsStack[len(b.ArgsStack)-1])

	var declarations bytes.Buffer
	if len(args) > 0 {
		declarations.WriteString("let stack = p.vstack.last().cloned().unwrap_or_default();\n")
		for _, arg := range args {
			fmt.Fprintf(
				&declarations,
				"let %s = stack.get(%s).cloned().unwrap_or(Value::Null);\n",
				arg,
				quoteRust(arg),
			)
		}
	}

	isPredicate := funcTpl == b.CallPredFuncTemplate
	returnType := "Value"
	fallback := "Value::Null"
	if isPredicate {
		returnType = "bool"
		fallback = "false"
	}

	b.Writeln("")
	b.Writelnf("fn _call%s(p: &mut PigeonParser) -> %s {", b.FuncName(funcIx), returnType)
	b.Indent()
	if declarations.Len() > 0 {
		for _, line := range strings.Split(strings.TrimSuffix(declarations.String(), "\n"), "\n") {
			b.Writeln(line)
		}
	}
	b.Writeln("let c = p.cur.clone();")
	if value != "" {
		for _, line := range strings.Split(value, "\n") {
			b.Writeln(strings.TrimRight(line, " \t\r"))
		}
	}
	b.Writeln(fallback)
	b.Dedent()
	b.Writeln("}")
}

func quoteRust(value string) string {
	var out strings.Builder
	out.WriteByte('"')
	for _, r := range value {
		switch r {
		case '\\':
			out.WriteString(`\\`)
		case '"':
			out.WriteString(`\"`)
		case '\n':
			out.WriteString(`\n`)
		case '\r':
			out.WriteString(`\r`)
		case '\t':
			out.WriteString(`\t`)
		case '\b':
			out.WriteString(`\x08`)
		case '\f':
			out.WriteString(`\x0C`)
		default:
			if r < 0x20 || r == 0x7f {
				fmt.Fprintf(&out, `\x%02X`, r)
			} else if r == 0x2028 || r == 0x2029 {
				fmt.Fprintf(&out, `\u{%X}`, r)
			} else {
				out.WriteRune(r)
			}
		}
	}
	out.WriteByte('"')
	return out.String()
}
