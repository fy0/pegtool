package builder_rust

import (
	"bytes"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"github.com/fy0/pegtool/bootstrap"
)

func TestGeneratedParserCompilesAndRuns(t *testing.T) {
	rustc := requireTool(t, "rustc")
	grammar := `{
{{ if eq .Target "rust" }}
const TARGET_MARKER: &str = "rust";
{{ else }}
this branch must not be generated
{{ end }}
}
start = first:word rest:("," word)* !. {
    let mut values = vec![first.as_str().unwrap().to_string()];
    if let Value::Array(items) = rest {
        for item in items {
            if let Value::Array(sequence) = item {
                values.push(sequence[0].as_str().unwrap().to_string());
            }
        }
    }
    return Value::String(values.join("|"));
}
word = [\p{L}]+ { return Value::String(c.text.clone()); }
`

	p := bootstrap.NewParser()
	g, err := p.Parse("grammar.peg", strings.NewReader(grammar))
	if err != nil {
		t.Fatal(err)
	}

	var generated bytes.Buffer
	if err := BuildParser(&generated, g); err != nil {
		t.Fatal(err)
	}
	generated.WriteString(`
fn main() {
    match PTParser::parse("alpha,\u{4e16}\u{754c}") {
        Ok(Value::String(value)) if value == "alpha|\u{4e16}\u{754c}" => println!("{}", value),
        Ok(value) => panic!("unexpected parse result: {:?}", value),
        Err(error) => panic!("parse failed: {}", error),
    }
}
`)

	dir := t.TempDir()
	source := filepath.Join(dir, "main.rs")
	if err := os.WriteFile(source, generated.Bytes(), 0o600); err != nil {
		t.Fatal(err)
	}
	binary := filepath.Join(dir, "parser-test.exe")
	cmd := exec.Command(rustc, "--edition=2021", source, "-O", "-o", binary)
	if output, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("rustc failed: %v\n%s\nGenerated parser:\n%s", err, output, generated.String())
	}

	cmd = exec.Command(binary)
	if output, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("generated Rust parser failed: %v\n%s", err, output)
	} else if strings.TrimSpace(string(output)) != "alpha|\u4e16\u754c" {
		t.Fatalf("unexpected output %q", output)
	}
}

func requireTool(t *testing.T, name string) string {
	t.Helper()
	path, err := exec.LookPath(name)
	if err != nil {
		t.Skipf("%s is not installed", name)
	}
	return path
}
